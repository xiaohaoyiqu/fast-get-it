def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--format", action="store_true", help="Format the listed new files; default: check only")
    args = parser.parse_args()
    if importlib.util.find_spec("ruff") is None:
        print("Ruff is missing. Use .venv/Scripts/python.exe or install requirements-dev.txt.", file=sys.stderr)
        return 1
    commands = (
        ("Project baseline lint", "check", "--config", "ruff.toml", *TARGETS),
        ("Media workflow extended lint", "check", "--config", "ruff.toml", "--extend-select", "B,PLE", *AUDIT_TARGETS),
        (
            "New file formatting",
            "format",
            "--config",
            "ruff.toml",
            *(() if args.format else ("--check",)),
            *FORMAT_TARGETS,
        ),
    )
    failed = False
    for title, *command in commands:
        print(f"\n{title}", flush=True)
        result = subprocess.run([sys.executable, "-m", "ruff", *command], cwd=ROOT, check=False)
        failed = failed or result.returncode != 0
    return int(failed)


if __name__ == "__main__":
    raise SystemExit(main())
